/**
 * Returns all backgrounds designated for a specific season (plus the neutral standard)
 */
export function getSeasonalBackgrounds(season: Season | string | undefined): CustomBackground[] {
  if (!season) {
    return DEFAULT_BACKGROUNDS;
  }
  const seasonBgs = DEFAULT_BACKGROUNDS.filter(b => b.season === season);
  const neutralBg = DEFAULT_BACKGROUNDS.find(b => b.isNeutralDefault);

  return neutralBg ? [...seasonBgs, neutralBg] : seasonBgs;
}

/**
 * Returns the default recommended background for a given season
 */
export function getDefaultBackgroundForSeason(season: Season | string | undefined): CustomBackground {
  if (!season) {
    return DEFAULT_BACKGROUNDS[0];
  }
  const match = DEFAULT_BACKGROUNDS.find(b => b.season === season && b.isSeasonalDefault);
  if (match) return match;

  const firstSeasonMatch = DEFAULT_BACKGROUNDS.find(b => b.season === season);
  if (firstSeasonMatch) return firstSeasonMatch;

  return DEFAULT_BACKGROUNDS.find(b => b.isNeutralDefault) || DEFAULT_BACKGROUNDS[0];
}
